"""Lakes and national borders near Florina, for the radar card.

The radar has no basemap: a canvas, some range rings and four town dots. That
is enough to read where the rain is relative to you, and not enough to read
where it is at all once it is 60 km out.

Terrain shading was the first answer and is not possible. Open-Meteo's
elevation endpoint rate-limits after a handful of requests, and averaging a
grid enough to remove the point-sampling noise takes dozens. So the geography
is embedded instead, and nothing is fetched at runtime.

Source: `Natural Earth <https://www.naturalearthdata.com/>`_ (public domain),
1:10m lakes and admin-0 boundary lines, clipped to a 1.35 degree box around the
town and decimated to roughly one point per kilometre. That is finer than a
320 px canvas can resolve - a pixel is about 0.5 km - so the shapes below are
the whole of what matters and 6.8 KB of it.

Only the outer ring of each polygon is kept. The Prespa lakes have islands with
holes and a couple of the polygons are enclaves; at this size they are a pixel
or two and would read as dirt.

Regenerate with the recipe in docs/DESIGN.md.
"""

